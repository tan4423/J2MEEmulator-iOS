// Opt-in test of SLJIT-generated ARM64 code. Does not enable the VM JIT.
#include <errno.h>
#include <libkern/OSCacheControl.h>
#include <stdint.h>
#include <stdio.h>
#include <sys/mman.h>
#include <unistd.h>
#include "sljitLir.h"

int32_t treo_jit_probe(void) {
    struct sljit_compiler *compiler = sljit_create_compiler(NULL);
    if (!compiler) return -1;
    sljit_s32 err = sljit_emit_enter(compiler, 0, SLJIT_ARGS0(W), 1, 0, 0);
    if (!err) err = sljit_emit_return(compiler, SLJIT_MOV, SLJIT_IMM, 42);
    if (err) {
        sljit_free_compiler(compiler);
        return -100 - err;
    }

    const size_t size = (size_t)getpagesize();
    void *page = mmap(NULL, size, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANON, -1, 0);
    if (page == MAP_FAILED) {
        int map_error = errno;
        sljit_free_compiler(compiler);
        return -400 - map_error;
    }

    // SLJIT writes directly to our mapping: no MAP_JIT and no prewritten instructions.
    struct sljit_generate_code_buffer buffer = {
        .buffer = page,
        .size = (sljit_uw)size,
        .executable_offset = 0,
    };
    void *entry = sljit_generate_code(compiler, SLJIT_GENERATE_CODE_BUFFER, &buffer);
    err = sljit_get_compiler_error(compiler);
    sljit_uw code_size = sljit_get_generated_code_size(compiler);
    sljit_free_compiler(compiler);
    if (!entry || entry != page || code_size == 0 || code_size > size) {
        munmap(page, size);
        return entry ? -302 : -200 - err;
    }

    if (mprotect(page, size, PROT_READ | PROT_EXEC) != 0) {
        int protect_error = errno;
        munmap(page, size);
        return -500 - protect_error;
    }
    sys_icache_invalidate(page, (size_t)code_size);
    fprintf(stderr, "[TREO-JIT] Executing %lu bytes generated by SLJIT via RW-to-RX\n",
            (unsigned long)code_size);
    sljit_sw value = ((sljit_sw (*)(void))entry)();
    munmap(page, size);
    fprintf(stderr, "[TREO-JIT] SLJIT RW-to-RX probe returned %ld\n", (long)value);
    return value == 42 ? 42 : -301;
}
